static ed_u64 ed_rotr(ed_u64 x, unsigned n) {
    return (x >> n) | (x << (64u - n));
}

/** Docstring: One SHA-512 compression over a 128-byte block. */
static void ed_sha_block(ed_sha *c, const unsigned char *p) {
    ed_u64 w[80];
    ed_u64 a;
    ed_u64 b;
    ed_u64 cc;
    ed_u64 d;
    ed_u64 e;
    ed_u64 f;
    ed_u64 g;
    ed_u64 h;
    unsigned i;
    for (i = 0; i < 16u; i++) {
        unsigned k = i * 8u;
        w[i] = ((ed_u64)p[k] << 56) | ((ed_u64)p[k + 1u] << 48) |
               ((ed_u64)p[k + 2u] << 40) | ((ed_u64)p[k + 3u] << 32) |
               ((ed_u64)p[k + 4u] << 24) | ((ed_u64)p[k + 5u] << 16) |
               ((ed_u64)p[k + 6u] << 8) | (ed_u64)p[k + 7u];
    }
    for (i = 16u; i < 80u; i++) {
        ed_u64 s0 = ed_rotr(w[i - 15u], 1) ^ ed_rotr(w[i - 15u], 8) ^ (w[i - 15u] >> 7);
        ed_u64 s1 = ed_rotr(w[i - 2u], 19) ^ ed_rotr(w[i - 2u], 61) ^ (w[i - 2u] >> 6);
        w[i] = w[i - 16u] + s0 + w[i - 7u] + s1;
    }
    a = c->h[0];
    b = c->h[1];
    cc = c->h[2];
    d = c->h[3];
    e = c->h[4];
    f = c->h[5];
    g = c->h[6];
    h = c->h[7];
    for (i = 0; i < 80u; i++) {
        ed_u64 s1 = ed_rotr(e, 14) ^ ed_rotr(e, 18) ^ ed_rotr(e, 41);
        ed_u64 ch = (e & f) ^ ((~e) & g);
        ed_u64 t1 = h + s1 + ch + ed_k[i] + w[i];
        ed_u64 s0 = ed_rotr(a, 28) ^ ed_rotr(a, 34) ^ ed_rotr(a, 39);
        ed_u64 mj = (a & b) ^ (a & cc) ^ (b & cc);
        ed_u64 t2 = s0 + mj;
        h = g;
        g = f;
        f = e;
        e = d + t1;
        d = cc;
        cc = b;
        b = a;
        a = t1 + t2;
    }
    c->h[0] += a;
    c->h[1] += b;
    c->h[2] += cc;
    c->h[3] += d;
    c->h[4] += e;
    c->h[5] += f;
    c->h[6] += g;
    c->h[7] += h;
}

/** Docstring: Start a SHA-512 digest. */
void ed_sha512_init(ed_sha *c) {
    c->h[0] = 0x6a09e667f3bcc908ULL;
    c->h[1] = 0xbb67ae8584caa73bULL;
    c->h[2] = 0x3c6ef372fe94f82bULL;
    c->h[3] = 0xa54ff53a5f1d36f1ULL;
    c->h[4] = 0x510e527fade682d1ULL;
    c->h[5] = 0x9b05688c2b3e6c1fULL;
    c->h[6] = 0x1f83d9abfb41bd6bULL;
    c->h[7] = 0x5be0cd19137e2179ULL;
    c->lo = 0;
    c->hi = 0;
    c->used = 0;
}

/** Docstring: Feed bytes into a running SHA-512 digest. */
void ed_sha512_update(ed_sha *c, const unsigned char *data, unsigned long len) {
    unsigned long i = 0;
    ed_u64 bits = (ed_u64)len << 3;
    ed_u64 old = c->lo;
    c->lo += bits;
    if (c->lo < old)
        c->hi++;
    c->hi += (ed_u64)len >> 61;
    while (i < len) {
        unsigned long left = len - i;
        unsigned take = 128u - c->used;
        unsigned k;
        if ((unsigned long)take > left)
            take = (unsigned)left;
        for (k = 0; k < take; k++)
            c->buf[c->used + k] = data[i + k];
        c->used += take;
        i += take;
        if (c->used == 128u) {
            ed_sha_block(c, c->buf);
            c->used = 0;
        }
    }
}

/** Docstring: Finish a SHA-512 digest into 64 bytes, big-endian length. */
void ed_sha512_final(ed_sha *c, unsigned char out[64]) {
    unsigned k;
    unsigned i;
    c->buf[c->used++] = 0x80;
    if (c->used > 112u) {
        while (c->used < 128u)
            c->buf[c->used++] = 0;
        ed_sha_block(c, c->buf);
        c->used = 0;
    }
    while (c->used < 112u)
        c->buf[c->used++] = 0;
    for (k = 0; k < 8u; k++)
        c->buf[112u + k] = (unsigned char)(c->hi >> (56u - 8u * k));
    for (k = 0; k < 8u; k++)
        c->buf[120u + k] = (unsigned char)(c->lo >> (56u - 8u * k));
    ed_sha_block(c, c->buf);
    for (i = 0; i < 8u; i++) {
        unsigned b = i * 8u;
        unsigned s;
        for (s = 0; s < 8u; s++)
            out[b + s] = (unsigned char)(c->h[i] >> (56u - 8u * s));
    }
}

/** Docstring: Copy one field element. */
static void ed_fe_copy(ed_fe *r, const ed_fe *a) {
    r->v[0] = a->v[0];
    r->v[1] = a->v[1];
    r->v[2] = a->v[2];
    r->v[3] = a->v[3];
}

/** Docstring: Zero one field element. */
static void ed_fe_zero(ed_fe *r) {
    r->v[0] = 0;
    r->v[1] = 0;
    r->v[2] = 0;
    r->v[3] = 0;
}

/** Docstring: One as a field element. */
static void ed_fe_one(ed_fe *r) {
    r->v[0] = 1;
    r->v[1] = 0;
    r->v[2] = 0;
    r->v[3] = 0;
}

/** Docstring: Constant-time select between two field elements. */
static void ed_fe_cmov(ed_fe *r, const ed_fe *b, unsigned flag) {
    ed_u64 m = 0ULL - (ed_u64)(flag & 1u);
    r->v[0] ^= m & (r->v[0] ^ b->v[0]);
    r->v[1] ^= m & (r->v[1] ^ b->v[1]);
    r->v[2] ^= m & (r->v[2] ^ b->v[2]);
    r->v[3] ^= m & (r->v[3] ^ b->v[3]);
}

/** Docstring: 1 when a is at least b as 256-bit integers, else 0. */
static unsigned ed_fe_ge(const ed_fe *a, const ed_fe *b) {
    if (a->v[3] != b->v[3])
        return (a->v[3] > b->v[3]) ? 1u : 0u;
    if (a->v[2] != b->v[2])
        return (a->v[2] > b->v[2]) ? 1u : 0u;
    if (a->v[1] != b->v[1])
        return (a->v[1] > b->v[1]) ? 1u : 0u;
    return (a->v[0] >= b->v[0]) ? 1u : 0u;
}

/** Docstring: r holds a minus b, caller guarantees a above b. */
static void ed_fe_rawsub(ed_fe *r, const ed_fe *a, const ed_fe *b) {
    ed_u64 t0 = a->v[0] - b->v[0];
    ed_u64 c0 = (t0 > a->v[0]) ? 1u : 0u;
    ed_u64 d1 = a->v[1] - c0;
    ed_u64 c1 = (d1 > a->v[1]) ? 1u : 0u;
    ed_u64 t1 = d1 - b->v[1];
    ed_u64 c2 = (t1 > d1) ? 1u : 0u;
    ed_u64 bw1 = c1 | c2;
    ed_u64 d2 = a->v[2] - bw1;
    ed_u64 c3 = (d2 > a->v[2]) ? 1u : 0u;
    ed_u64 t2 = d2 - b->v[2];
    ed_u64 c4 = (t2 > d2) ? 1u : 0u;
    ed_u64 bw2 = c3 | c4;
    ed_u64 d3 = a->v[3] - bw2;
    ed_u64 t3 = d3 - b->v[3];
    r->v[0] = t0;
    r->v[1] = t1;
    r->v[2] = t2;
    r->v[3] = t3;
}

/** Docstring: r holds a plus b mod q with one conditional subtract. */
static void ed_fe_add(ed_fe *r, const ed_fe *a, const ed_fe *b) {
    __uint128_t c;
    ed_fe t;
    ed_fe q;
    c = (__uint128_t)a->v[0] + b->v[0];
    t.v[0] = (ed_u64)c;
    c = (__uint128_t)a->v[1] + b->v[1] + (ed_u64)(c >> 64);
    t.v[1] = (ed_u64)c;
    c = (__uint128_t)a->v[2] + b->v[2] + (ed_u64)(c >> 64);
    t.v[2] = (ed_u64)c;
    c = (__uint128_t)a->v[3] + b->v[3] + (ed_u64)(c >> 64);
    t.v[3] = (ed_u64)c;
    q.v[0] = ed_qq[0];
    q.v[1] = ed_qq[1];
    q.v[2] = ed_qq[2];
    q.v[3] = ed_qq[3];
    if ((ed_u64)(c >> 64) || ed_fe_ge(&t, &q))
        ed_fe_rawsub(&t, &t, &q);
    ed_fe_copy(r, &t);
}

/** Docstring: r holds a minus b mod q with borrow folded back. */
static void ed_fe_sub(ed_fe *r, const ed_fe *a, const ed_fe *b) {
    ed_u64 t0 = a->v[0] - b->v[0];
    ed_u64 c0 = (t0 > a->v[0]) ? 1u : 0u;
    ed_u64 d1 = a->v[1] - c0;
    ed_u64 c1 = (d1 > a->v[1]) ? 1u : 0u;
    ed_u64 t1 = d1 - b->v[1];
    ed_u64 c2 = (t1 > d1) ? 1u : 0u;
    ed_u64 borrow1 = c1 | c2;
    ed_u64 d2 = a->v[2] - borrow1;
    ed_u64 c3 = (d2 > a->v[2]) ? 1u : 0u;
    ed_u64 t2 = d2 - b->v[2];
    ed_u64 c4 = (t2 > d2) ? 1u : 0u;
    ed_u64 borrow2 = c3 | c4;
    ed_u64 d3 = a->v[3] - borrow2;
    ed_u64 c5 = (d3 > a->v[3]) ? 1u : 0u;
    ed_u64 t3 = d3 - b->v[3];
    ed_u64 c6 = (t3 > d3) ? 1u : 0u;
    ed_u64 borrow3 = c5 | c6;
    __uint128_t c;
    ed_fe t;
    ed_fe q;
    t.v[0] = t0;
    t.v[1] = t1;
    t.v[2] = t2;
    t.v[3] = t3;
    if (borrow3) {
        q.v[0] = ed_qq[0];
        q.v[1] = ed_qq[1];
        q.v[2] = ed_qq[2];
        q.v[3] = ed_qq[3];
        c = (__uint128_t)t.v[0] + q.v[0];
        t.v[0] = (ed_u64)c;
        c = (__uint128_t)t.v[1] + q.v[1] + (ed_u64)(c >> 64);
        t.v[1] = (ed_u64)c;
        c = (__uint128_t)t.v[2] + q.v[2] + (ed_u64)(c >> 64);
        t.v[2] = (ed_u64)c;
        t.v[3] = t.v[3] + q.v[3] + (ed_u64)(c >> 64);
    }
    ed_fe_copy(r, &t);
}

/** Docstring: Fold eight limbs mod q with three 38-fold passes. */
static void ed_fe_fold(ed_fe *r, ed_u64 w[8]) {
    unsigned round;
    ed_fe t;
    ed_fe q;
    for (round = 0; round < 3u; round++) {
        __uint128_t c;
        c = (__uint128_t)w[4] * 38u + w[0];
        w[0] = (ed_u64)c;
        c = (__uint128_t)w[5] * 38u + w[1] + (ed_u64)(c >> 64);
        w[1] = (ed_u64)c;
        c = (__uint128_t)w[6] * 38u + w[2] + (ed_u64)(c >> 64);
        w[2] = (ed_u64)c;
        c = (__uint128_t)w[7] * 38u + w[3] + (ed_u64)(c >> 64);
        w[3] = (ed_u64)c;
        w[4] = (ed_u64)(c >> 64);
        w[5] = 0;
        w[6] = 0;
        w[7] = 0;
    }
    t.v[0] = w[0];
    t.v[1] = w[1];
    t.v[2] = w[2];
    t.v[3] = w[3];
    q.v[0] = ed_qq[0];
    q.v[1] = ed_qq[1];
    q.v[2] = ed_qq[2];
    q.v[3] = ed_qq[3];
    if (w[4] || ed_fe_ge(&t, &q)) {
        ed_fe back;
        back.v[0] = w[4] * 38u;
        back.v[1] = 0;
        back.v[2] = 0;
        back.v[3] = 0;
        ed_fe_add(&t, &t, &back);
        if (ed_fe_ge(&t, &q))
            ed_fe_rawsub(&t, &t, &q);
        if (ed_fe_ge(&t, &q))
            ed_fe_rawsub(&t, &t, &q);
    }
    ed_fe_copy(r, &t);
}

/** Docstring: r holds a times b mod q, schoolbook over 128-bit lanes. */
static void ed_fe_mul(ed_fe *r, const ed_fe *a, const ed_fe *b) {
    __uint128_t acc;
    ed_u64 t[8];
    unsigned i;
    unsigned j;
    for (i = 0; i < 8u; i++)
        t[i] = 0;
    for (i = 0; i < 4u; i++) {
        __uint128_t carry;
        unsigned k;
        acc = 0;
        for (j = 0; j < 4u; j++) {
            acc += (__uint128_t)a->v[i] * b->v[j] + t[i + j];
            t[i + j] = (ed_u64)acc;
            acc >>= 64;
        }
        carry = acc;
        k = i + 4u;
        while (carry && k < 8u) {
            __uint128_t s = (__uint128_t)t[k] + (ed_u64)carry;
            t[k] = (ed_u64)s;
            carry = s >> 64;
            k++;
        }
    }
    ed_fe_fold(r, t);
}

/** Docstring: r holds a squared mod q. */
static void ed_fe_sq(ed_fe *r, const ed_fe *a) {
    ed_fe_mul(r, a, a);
}

/** Docstring: r holds a to the e mod q, MSB first, always square. */
static void ed_fe_pow(ed_fe *r, const ed_fe *a, const unsigned char *bits, unsigned nbits) {
    ed_fe acc;
    ed_fe tmp;
    unsigned i;
    ed_fe_one(&acc);
    for (i = 0; i < nbits; i++) {
        ed_fe_sq(&tmp, &acc);
        ed_fe_copy(&acc, &tmp);
        ed_fe_mul(&tmp, &acc, a);
        ed_fe_cmov(&acc, &tmp, bits[i]);
    }
    ed_fe_copy(r, &acc);
}

/** Docstring: r holds one over a mod q via Fermat, exponent q minus 2.
 *
 * q minus 2 keeps bits 0, 1, 3 and 5..254 set with 2 and 4 clear. */
static void ed_fe_inv(ed_fe *r, const ed_fe *a) {
    unsigned char bits[255];
    unsigned i;
    for (i = 0; i < 255u; i++)
        bits[i] = 1;
    bits[252u] = 0;
    bits[250u] = 0;
    ed_fe_pow(r, a, bits, 255u);
}

/** Docstring: Load 32 little-endian bytes into a field element. */
static void ed_fe_frombytes(ed_fe *r, const unsigned char b[32]) {
    unsigned i;
    unsigned k;
    for (i = 0; i < 4u; i++) {
        ed_u64 w = 0;
        for (k = 0; k < 8u; k++)
            w |= (ed_u64)b[i * 8u + k] << (8u * k);
        r->v[i] = w;
    }
}

/** Docstring: Store a field element as 32 little-endian bytes. */
static void ed_fe_tobytes(unsigned char b[32], const ed_fe *a) {
    unsigned i;
    unsigned k;
    for (i = 0; i < 4u; i++)
        for (k = 0; k < 8u; k++)
            b[i * 8u + k] = (unsigned char)(a->v[i] >> (8u * k));
}

/** Docstring: 1 when a equals b limb-wise, else 0. */
static unsigned ed_fe_eq(const ed_fe *a, const ed_fe *b) {
    ed_u64 d = (a->v[0] ^ b->v[0]) | (a->v[1] ^ b->v[1]) |
               (a->v[2] ^ b->v[2]) | (a->v[3] ^ b->v[3]);
    return (d == 0u) ? 1u : 0u;
}

/** Docstring: 1 when the 32-byte value is canonical, below q. */
static unsigned ed_bytes_lt_q(const unsigned char b[32]) {
    unsigned i = 32u;
    while (i > 0u) {
        unsigned char qb;
        i--;
        if (i == 31u)
            qb = 0x7f;
        else if (i == 0u)
            qb = 0xed;
        else
            qb = 0xff;
        if (b[i] != qb)
            return (b[i] < qb) ? 1u : 0u;
    }
    return 1u;
}

/** Docstring: 1 when the 32-byte scalar is canonical, below L. */
static unsigned ed_scalar_lt_l(const unsigned char b[32]) {
    unsigned i = 32u;
    while (i > 0u) {
        unsigned char lb;
        i--;
        if (i < 8u)
            lb = (unsigned char)(ed_ll[0] >> (8u * i));
        else if (i < 16u)
            lb = (unsigned char)(ed_ll[1] >> (8u * (i - 8u)));
        else if (i < 24u)
            lb = 0;
        else if (i < 31u)
            lb = 0;
        else
            lb = 0x10;
        if (b[i] != lb)
            return (b[i] < lb) ? 1u : 0u;
    }
    return 1u;
}

/** Docstring: Subtract the 320-bit order from a 320-bit remainder. */
static void ed_rem_sub(ed_u64 r[5], const ed_u64 a[5], const ed_u64 b[5]) {
    ed_u64 t0 = a[0] - b[0];
    ed_u64 c0 = (t0 > a[0]) ? 1u : 0u;
    ed_u64 d1 = a[1] - c0;
    ed_u64 c1 = (d1 > a[1]) ? 1u : 0u;
    ed_u64 t1 = d1 - b[1];
    ed_u64 c2 = (t1 > d1) ? 1u : 0u;
    ed_u64 bw1 = c1 | c2;
    ed_u64 d2 = a[2] - bw1;
    ed_u64 c3 = (d2 > a[2]) ? 1u : 0u;
    ed_u64 t2 = d2 - b[2];
    ed_u64 c4 = (t2 > d2) ? 1u : 0u;
    ed_u64 bw2 = c3 | c4;
    ed_u64 d3 = a[3] - bw2;
    ed_u64 c5 = (d3 > a[3]) ? 1u : 0u;
    ed_u64 t3 = d3 - b[3];
    ed_u64 c6 = (t3 > d3) ? 1u : 0u;
    ed_u64 bw3 = c5 | c6;
    ed_u64 d4 = a[4] - bw3;
    ed_u64 t4 = d4 - b[4];
    r[0] = t0;
    r[1] = t1;
    r[2] = t2;
    r[3] = t3;
    r[4] = t4;
}

/** Docstring: 1 when the 320-bit a holds at least b, else 0. */
static unsigned ed_rem_ge(const ed_u64 a[5], const ed_u64 b[5]) {
    if (a[4] != b[4])
        return (a[4] > b[4]) ? 1u : 0u;
    if (a[3] != b[3])
        return (a[3] > b[3]) ? 1u : 0u;
    if (a[2] != b[2])
        return (a[2] > b[2]) ? 1u : 0u;
    if (a[1] != b[1])
        return (a[1] > b[1]) ? 1u : 0u;
    return (a[0] >= b[0]) ? 1u : 0u;
}
/** Docstring: Reduce a 64-byte digest mod L by binary long division. */
static void ed_mod_l(ed_fe *r, const unsigned char h[64]) {
    ed_u64 rem[5];
    ed_u64 lv[5];
    ed_u64 tmp[5];
    unsigned b;
    unsigned k;
    unsigned s;
    for (k = 0; k < 5u; k++)
        rem[k] = 0;
    lv[0] = ed_ll[0];
    lv[1] = ed_ll[1];
    lv[2] = 0;
    lv[3] = ed_ll[3];
    lv[4] = 0;
    for (b = 0; b < 512u; b++) {
        unsigned src = 63u - (b / 8u);
        unsigned bit = 7u - (b % 8u);
        unsigned carry = (unsigned)((h[src] >> bit) & 1u);
        unsigned nk;
        for (nk = 0; nk < 5u; nk++) {
            unsigned nc = (unsigned)(rem[nk] >> 63);
            rem[nk] = (rem[nk] << 1) | carry;
            carry = nc;
        }
        for (s = 0; s < 4u; s++) {
            if (ed_rem_ge(rem, lv)) {
                ed_rem_sub(tmp, rem, lv);
                for (nk = 0; nk < 5u; nk++)
                    rem[nk] = tmp[nk];
            }
        }
    }
    r->v[0] = rem[0];
    r->v[1] = rem[1];
    r->v[2] = rem[2];
    r->v[3] = rem[3];
}

/** Docstring: Copy one extended point. */
static void ed_ge_copy(ed_ge *r, const ed_ge *a) {
    ed_fe_copy(&r->x, &a->x);
    ed_fe_copy(&r->y, &a->y);
    ed_fe_copy(&r->z, &a->z);
    ed_fe_copy(&r->t, &a->t);
}

/** Docstring: Constant-time point select for the scalar multiply. */
static void ed_ge_cmov(ed_ge *r, const ed_ge *b, unsigned flag) {
    ed_fe_cmov(&r->x, &b->x, flag);
    ed_fe_cmov(&r->y, &b->y, flag);
    ed_fe_cmov(&r->z, &b->z, flag);
    ed_fe_cmov(&r->t, &b->t, flag);
}

/** Docstring: Complete twisted-Edwards addition, valid for all inputs. */
static void ed_ge_add(ed_ge *r, const ed_ge *p, const ed_ge *q, const ed_fe *d2) {
    ed_fe a;
    ed_fe b;
    ed_fe c;
    ed_fe d;
    ed_fe e;
    ed_fe f;
    ed_fe g;
    ed_fe h;
    ed_fe t0;
    ed_fe t1;
    ed_fe_sub(&t0, &p->y, &p->x);
    ed_fe_sub(&t1, &q->y, &q->x);
    ed_fe_mul(&a, &t0, &t1);
    ed_fe_add(&t0, &p->y, &p->x);
    ed_fe_add(&t1, &q->y, &q->x);
    ed_fe_mul(&b, &t0, &t1);
    ed_fe_mul(&t0, &p->t, &q->t);
    ed_fe_mul(&c, &t0, d2);
    ed_fe_add(&t0, &p->z, &p->z);
    ed_fe_mul(&d, &t0, &q->z);
    ed_fe_sub(&e, &b, &a);
    ed_fe_sub(&f, &d, &c);
    ed_fe_add(&g, &d, &c);
    ed_fe_add(&h, &b, &a);
    ed_fe_mul(&r->x, &e, &f);
    ed_fe_mul(&r->y, &g, &h);
    ed_fe_mul(&r->z, &f, &g);
    ed_fe_mul(&r->t, &e, &h);
}

/** Docstring: Twisted-Edwards doubling for a fixed at minus one. */
static void ed_ge_double(ed_ge *r, const ed_ge *p) {
    ed_fe a;
    ed_fe b;
    ed_fe c;
    ed_fe e;
    ed_fe f;
    ed_fe g;
    ed_fe h;
    ed_fe t0;
    ed_fe t1;
    ed_fe_sq(&a, &p->x);
    ed_fe_sq(&b, &p->y);
    ed_fe_sq(&t0, &p->z);
    ed_fe_add(&c, &t0, &t0);
    ed_fe_add(&t0, &p->x, &p->y);
    ed_fe_sq(&t0, &t0);
    ed_fe_sub(&t1, &t0, &a);
    ed_fe_sub(&e, &t1, &b);
    ed_fe_add(&g, &b, &b);
    {
        ed_fe na;
        ed_fe_zero(&na);
        ed_fe_sub(&na, &na, &a);
        ed_fe_add(&g, &na, &b);
    }
    ed_fe_sub(&f, &g, &c);
    {
        ed_fe na;
        ed_fe nb;
        ed_fe_zero(&na);
        ed_fe_zero(&nb);
        ed_fe_sub(&na, &na, &a);
        ed_fe_sub(&nb, &nb, &b);
        ed_fe_add(&h, &na, &nb);
    }
    ed_fe_mul(&r->x, &e, &f);
    ed_fe_mul(&r->y, &g, &h);
    ed_fe_mul(&r->z, &f, &g);
    ed_fe_mul(&r->t, &e, &h);
}

/** Docstring: r holds p times the 32-byte little-endian scalar. */
static void ed_ge_scalarmult(ed_ge *r, const ed_ge *p, const unsigned char s[32],
                             const ed_fe *d2) {
    ed_ge q;
    ed_ge dbl;
    int i;
    ed_fe_zero(&q.x);
    ed_fe_one(&q.y);
    ed_fe_one(&q.z);
    ed_fe_zero(&q.t);
    for (i = 254; i >= 0; i--) {
        unsigned bit = (unsigned)((s[i >> 3] >> (i & 7)) & 1u);
        ed_ge_double(&dbl, &q);
        ed_ge_copy(&q, &dbl);
        ed_ge_add(&dbl, &q, p, d2);
        ed_ge_cmov(&q, &dbl, bit);
    }
    ed_ge_copy(r, &q);
}

/** Docstring: Recover the curve constant d from minus 121665 over 121666. */
static void ed_curve_d(ed_fe *d) {
    ed_fe num;
    ed_fe den;
    ed_fe inv;
    ed_fe_one(&num);
    ed_fe_zero(&den);
    ed_fe_sub(&num, &num, &num);
    num.v[0] = 121665;
    den.v[0] = 121666;
    ed_fe_inv(&inv, &den);
    ed_fe_mul(d, &num, &inv);
    {
        ed_fe zero;
        ed_fe_zero(&zero);
        ed_fe_sub(d, &zero, d);
    }
}

/** Docstring: Decode a point encoding into affine x/y, 1 on success.
 *
 * Rejects non-canonical y at or above q, a missing square root and a
 * sign mismatch after the sqrt(-1) adjustment. The adjustment root
 * itself comes from pow(2, (q-1)/4) computed at run time. */
static int ed_ge_frombytes(ed_fe *x_out, ed_fe *y_out, const unsigned char s[32],
                           const ed_fe *d) {
    unsigned char yraw[32];
    unsigned sign;
    ed_fe y;
    ed_fe y2;
    ed_fe one;
    ed_fe num;
    ed_fe den;
    ed_fe deninv;
    ed_fe x2;
    ed_fe x;
    ed_fe xx;
    ed_fe diff;
    ed_fe two;
    unsigned i;
    unsigned char bits[253];
    unsigned char xbyte0;
    for (i = 0; i < 32u; i++)
        yraw[i] = s[i];
    sign = (unsigned)(yraw[31] >> 7);
    yraw[31] &= 0x7f;
    if (!ed_bytes_lt_q(yraw))
        return 0;
    ed_fe_frombytes(&y, yraw);
    ed_fe_one(&one);
    two.v[0] = 2;
    two.v[1] = 0;
    two.v[2] = 0;
    two.v[3] = 0;
    ed_fe_sq(&y2, &y);
    ed_fe_sub(&num, &y2, &one);
    ed_fe_mul(&den, d, &y2);
    ed_fe_add(&den, &den, &one);
    ed_fe_inv(&deninv, &den);
    ed_fe_mul(&x2, &num, &deninv);
    for (i = 0; i < 253u; i++)
        bits[i] = 0;
    for (i = 1u; i < 252u; i++)
        bits[253u - 1u - i] = 1;
    ed_fe_pow(&x, &x2, bits, 253u);
    ed_fe_sq(&xx, &x);
    ed_fe_sub(&diff, &xx, &x2);
    if (diff.v[0] | diff.v[1] | diff.v[2] | diff.v[3]) {
        ed_fe sqrtm1;
        ed_fe adj;
        for (i = 0; i < 253u; i++)
            bits[i] = 0;
        bits[252u] = 1;
        bits[251u] = 1;
        for (i = 3u; i < 253u; i++)
            bits[253u - 1u - i] = 1;
        ed_fe_pow(&sqrtm1, &two, bits, 253u);
        ed_fe_mul(&adj, &x, &sqrtm1);
        ed_fe_copy(&x, &adj);
        ed_fe_sq(&xx, &x);
        ed_fe_sub(&diff, &xx, &x2);
        if (diff.v[0] | diff.v[1] | diff.v[2] | diff.v[3])
            return 0;
    }
    {
        unsigned char xb[32];
        ed_fe_tobytes(xb, &x);
        xbyte0 = xb[0];
    }
    if (((unsigned)xbyte0 & 1u) != sign) {
        ed_fe zero;
        ed_fe_zero(&zero);
        ed_fe_sub(&x, &zero, &x);
    }
    ed_fe_copy(x_out, &x);
    ed_fe_copy(y_out, &y);
    return 1;
}

/** Docstring: Verify an Ed25519 signature, 1 valid else 0 fail-closed.
 *
 * Rejects S at or above L and non-canonical R/A encodings before any
 * curve work, then checks [S]B minus [h]A against R by
 * cross-multiplied projective comparison, so no inversion touches
 * the hot path. Null inputs refuse. */
int ed25519_verify(const unsigned char sig[64], const unsigned char *msg,
                   unsigned long msglen, const unsigned char pub[32]) {
    unsigned char rraw[32];
    unsigned char sbytes[32];
    ed_fe rx;
    ed_fe ry;
    ed_fe ax;
    ed_fe ay;
    ed_fe d;
    ed_fe d2;
    ed_ge base;
    ed_ge apt;
    ed_ge p1;
    ed_ge p2;
    ed_ge neg;
    ed_ge diff;
    ed_sha c;
    unsigned char hbuf[64];
    ed_fe h;
    unsigned char hbytes[32];
    ed_fe zx;
    ed_fe wx;
    ed_fe zy;
    ed_fe wy;
    ed_fe zero;
    unsigned i;
    if (!sig || !pub)
        return 0;
    if (!msg && msglen)
        return 0;
    for (i = 0; i < 32u; i++) {
        rraw[i] = sig[i];
        sbytes[i] = sig[32u + i];
    }
    if (!ed_scalar_lt_l(sbytes))
        return 0;
    ed_curve_d(&d);
    ed_fe_add(&d2, &d, &d);
    if (!ed_ge_frombytes(&rx, &ry, rraw, &d))
        return 0;
    if (!ed_ge_frombytes(&ax, &ay, pub, &d))
        return 0;
    ed_sha512_init(&c);
    ed_sha512_update(&c, sig, 32ul);
    ed_sha512_update(&c, pub, 32ul);
    if (msglen)
        ed_sha512_update(&c, msg, msglen);
    ed_sha512_final(&c, hbuf);
    ed_mod_l(&h, hbuf);
    ed_fe_tobytes(hbytes, &h);
    if (!ed_ge_frombytes(&base.x, &base.y, ed_braw, &d))
        return 0;
    ed_fe_one(&base.z);
    ed_fe_mul(&base.t, &base.x, &base.y);
    ed_fe_copy(&apt.x, &ax);
    ed_fe_copy(&apt.y, &ay);
    ed_fe_one(&apt.z);
    ed_fe_mul(&apt.t, &ax, &ay);
    ed_ge_scalarmult(&p1, &base, sbytes, &d2);
    ed_ge_scalarmult(&p2, &apt, hbytes, &d2);
    ed_fe_zero(&zero);
    ed_fe_sub(&neg.x, &zero, &p2.x);
    ed_fe_copy(&neg.y, &p2.y);
    ed_fe_copy(&neg.z, &p2.z);
    ed_fe_sub(&neg.t, &zero, &p2.t);
    ed_ge_add(&diff, &p1, &neg, &d2);
    ed_fe_mul(&zx, &diff.x, &diff.z);
    ed_fe_mul(&wx, &rx, &diff.z);
    ed_fe_mul(&wx, &wx, &diff.z);
    if (!ed_fe_eq(&zx, &wx))
        return 0;
    ed_fe_mul(&zy, &diff.y, &diff.z);
    ed_fe_mul(&wy, &ry, &diff.z);
    ed_fe_mul(&wy, &wy, &diff.z);
    if (!ed_fe_eq(&zy, &wy))
        return 0;
    return 1;
}
